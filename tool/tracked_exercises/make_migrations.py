#!/usr/bin/env python3
"""Writes reed/migrations/2026_10_27_01_tracked_exercises.up.sql from e4_app_bundle/exercise_catalog.json (and copies
the catalogue to reed/data/, which the PHP seed reads). Run it again after changing the catalogue:

    python tool/tracked_exercises/make_migrations.py
"""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "e4_app_bundle" / "exercise_catalog.json"
OUT = ROOT / "reed" / "migrations" / "2026_10_27_01_tracked_exercises.up.sql"


def q(v):
    if v is None:
        return "NULL"
    return "'" + str(v).replace("\\", "\\\\").replace("'", "''") + "'"


def compact(v):
    """JSON as PHP json_encode(v, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES) writes it."""
    return json.dumps(v, ensure_ascii=False, separators=(",", ":"))


def main():
    cat = json.loads(CATALOG.read_text(encoding="utf-8"))
    lines = [
        "-- Tracked exercises (e1-e4) and their body regions, from e4_app_bundle/exercise_catalog.json",
        "-- (generated by tool/tracked_exercises/make_migrations.py). Idempotent: running it twice changes nothing.",
        "-- Undo: 2026_10_27_01_tracked_exercises.down.sql. The PHP endpoints do the same on first use",
        "-- (reed/tracked_exercises_lib.php: ensure_tracking_schema).",
        "CREATE TABLE IF NOT EXISTS `body_region` (",
        "  `id` VARCHAR(16) NOT NULL PRIMARY KEY,",
        "  `label` VARCHAR(64) NOT NULL,",
        "  `display_order` INT NOT NULL",
        ") DEFAULT CHARSET=utf8mb4;",
        "",
        "CREATE TABLE IF NOT EXISTS `tracked_exercise` (",
        "  `id` VARCHAR(8) NOT NULL PRIMARY KEY,",
        "  `body_region` VARCHAR(16) NOT NULL,",
        "  `display_order` INT NOT NULL,",
        "  `name` VARCHAR(255) NOT NULL,",
        "  `side_kind` VARCHAR(8) NOT NULL,",
        "  `side_question` VARCHAR(255) NOT NULL,",
        "  `side_meaning` VARCHAR(255) NOT NULL,",
        "  `camera` TEXT NULL,",
        "  `instructions` TEXT NOT NULL,",
        "  `classes` TEXT NOT NULL,",
        "  `model_bundle` VARCHAR(64) NOT NULL,",
        "  `model_config` VARCHAR(64) NOT NULL,",
        "  `model_file` VARCHAR(64) NOT NULL,",
        "  KEY `idx_tracked_region` (`body_region`, `display_order`),",
        "  CONSTRAINT `fk_tracked_region` FOREIGN KEY (`body_region`) REFERENCES `body_region` (`id`),",
        "  CONSTRAINT `chk_tracked_side_kind` CHECK (`side_kind` IN ('arm', 'leg'))",
        ") DEFAULT CHARSET=utf8mb4;",
        "",
    ]
    for r in cat["regions"]:
        lines.append(
            f"INSERT INTO `body_region` (`id`, `label`, `display_order`) VALUES ({q(r['id'])}, {q(r['label'])}, "
            f"{int(r['order'])})\n  ON DUPLICATE KEY UPDATE `label` = VALUES(`label`), "
            f"`display_order` = VALUES(`display_order`);")
    lines.append("")
    cols = ["id", "body_region", "display_order", "name", "side_kind", "side_question", "side_meaning", "camera",
            "instructions", "classes", "model_bundle", "model_config", "model_file"]
    for e in cat["exercises"]:
        vals = [q(e["id"]), q(e["region"]), str(int(e["order"])), q(e["name"]),
                q("leg" if e["region"] == "hip" else "arm"), q(e["side_question"]), q(e["side_meaning"]),
                q(e.get("camera")), q(compact(e["instructions"])),
                q(compact(e["classes"])), q(e["model"]["bundle"]), q(e["model"]["config"]),
                q(e["model"]["file"])]
        upd = ", ".join(f"`{c}` = VALUES(`{c}`)" for c in cols[1:])
        lines.append(f"INSERT INTO `tracked_exercise` ({', '.join('`' + c + '`' for c in cols)})\n"
                     f"  VALUES ({', '.join(vals)})\n  ON DUPLICATE KEY UPDATE {upd};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    shutil.copyfile(CATALOG, ROOT / "reed" / "data" / "exercise_catalog.json")
    print("written", OUT)


if __name__ == "__main__":
    main()
